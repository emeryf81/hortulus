/** The custom properties for a theme attribute ("classic", "earth", "season-autumn" ...) in light or dark. */
export function paletteFor(theme: string, dark: boolean): Palette {
  return dark ? { ...DARK, ...(THEME_DARK[theme] ?? {}) } : { ...(THEME_LIGHT[theme] ?? {}) };
}
